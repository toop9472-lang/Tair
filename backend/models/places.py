"""مطابقة المدينة: الاسم المختصر واسم الدولة يشمل مدنها."""

# اختيار الدولة أو الاسم الدارج يجد الإعلان المحفوظ بالمدينة.
CITY_QUERY_ALIASES = {
    "مكة المكرمة": ["مكة"],
    "مكة": ["مكة المكرمة"],
    "المدينة المنورة": ["المدينة"],
    "المدينة": ["المدينة المنورة"],
    "الأحساء": ["الهفوف"],
    "الهفوف": ["الأحساء"],
    "الإمارات العربية المتحدة": [
        "دبي", "أبوظبي", "الشارقة", "عجمان", "أم القيوين",
        "رأس الخيمة", "الفجيرة", "العين",
    ],
    "البحرين": ["المنامة", "المحرق", "الرفاع", "مدينة عيسى", "سترة"],
    "قطر": ["الدوحة", "الريان", "الوكرة", "الخور", "أم صلال"],
    "الكويت": ["مدينة الكويت", "حولي", "الفروانية", "الأحمدي", "الجهراء", "مبارك الكبير"],
    "سلطنة عمان": ["مسقط", "صلالة", "صحار", "نزوى", "صور", "البريمي"],
}


def city_match_values(city: str):
    name = (city or "").strip()
    if not name:
        return []
    return [name, *CITY_QUERY_ALIASES.get(name, [])]
